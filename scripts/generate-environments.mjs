// Writes src/environments/environment*.ts from .env (or the shell environment)
// so URLs stay out of git. Angular swaps environment.development.ts in for
// development builds via fileReplacements in angular.json.
import { existsSync, writeFileSync } from "node:fs";

const ENV_FILE = ".env";
const OUTPUT_DIR = "src/environments";

const ENVIRONMENTS = [
	{ file: "environment.ts", prefix: "PROD" },
	{ file: "environment.development.ts", prefix: "DEV" }
];

if (existsSync(ENV_FILE)) {
	// Does not override variables already set in the shell.
	process.loadEnvFile(ENV_FILE);
}

function requireVariable(name) {
	const value = process.env[name];
	if (!value) {
		throw new Error(
			`${name} is not set. Add it to .env (see README "Getting started").`
		);
	}
	return value;
}

for (const { file, prefix } of ENVIRONMENTS) {
	const environment = {
		apiEndpoint: requireVariable(`${prefix}_API_URL`),
		bluemapUrl: requireVariable(`${prefix}_BLUEMAP_URL`)
	};
	writeFileSync(
		`${OUTPUT_DIR}/${file}`,
		`// Generated by scripts/generate-environments.mjs from .env; do not edit.
import { IEnvironment } from './environment.interface';

export const environment: IEnvironment = ${JSON.stringify(environment, null, "\t")};
`
	);
}
