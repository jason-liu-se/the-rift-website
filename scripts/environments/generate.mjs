// Writes src/environments/ (and the crawler files, see ../seo/) from .env, the
// shell, and NAME=value arguments so URLs stay out of git. Angular swaps environment.development.ts in for
// development builds via fileReplacements in angular.json.
//
// Usage: node scripts/environments/generate.mjs [--require-prod] [NAME=value...]
//
// Only variables named PUBLIC_X, DEV_PUBLIC_X, or PROD_PUBLIC_X are read,
// because every value ends up in the public JS bundle; anything else (secrets,
// system variables) is ignored. Each becomes `environment.X`, with DEV_ and
// PROD_ overriding PUBLIC_X in that environment. IEnvironment is generated from
// the resulting keys. Per-variable settings live in config.mjs.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { parseArgs, parseEnv } from "node:util";
import { DEV_DEFAULTS, PROCESSORS } from "./config.mjs";
import { writeCrawlerFiles } from "../seo/crawler-files.mjs";

const ENV_FILE = ".env";
const OUTPUT_DIR = "src/environments";
// Captures the environment prefix ("", "DEV_" or "PROD_") and the code name.
const PUBLIC_NAME = /^(DEV_|PROD_)?PUBLIC_(\w+)$/;

const { values: options, positionals } = parseArgs({
	options: { "require-prod": { type: "boolean", default: false } },
	allowPositionals: true
});

/** Parses NAME=value command-line arguments, which must be public. */
function parseArgumentVariables(args) {
	return Object.fromEntries(
		args.map((arg) => {
			const [name, ...value] = arg.split("=");
			if (!value.length || !PUBLIC_NAME.test(name)) {
				throw new Error(
					`Expected [DEV_|PROD_]PUBLIC_<NAME>=value, got "${arg}".`
				);
			}
			return [name, value.join("=")];
		})
	);
}

/**
 * Non-empty public values by environment prefix, then code name. Later
 * sources win: .env, then the shell, then command-line arguments.
 */
function readVariables(args) {
	const all = {
		...(existsSync(ENV_FILE)
			? parseEnv(readFileSync(ENV_FILE, "utf8"))
			: {}),
		...process.env,
		...parseArgumentVariables(args)
	};
	const byPrefix = { "": {}, DEV_: {}, PROD_: {} };
	for (const [name, value] of Object.entries(all)) {
		const [, prefix = "", codeName] = name.match(PUBLIC_NAME) ?? [];
		if (codeName && value) {
			byPrefix[prefix][codeName] = value;
		}
	}
	return byPrefix;
}

const { "": general, DEV_: dev, PROD_: prod } = readVariables(positionals);
const development = { ...DEV_DEFAULTS, ...general, ...dev };
const production = {
	...(options["require-prod"] ? general : development),
	...prod
};

// Both files must match IEnvironment, so each needs every key.
const names = [
	...new Set([...Object.keys(development), ...Object.keys(production)])
].sort();

/** Checks and processes `environment`, naming variables with `prefix`. */
function finalise(environment, prefix) {
	const missing = names.filter((name) => !(name in environment));
	if (missing.length) {
		const list = missing.map(
			(name) => `${prefix}PUBLIC_${name} (or PUBLIC_${name})`
		);
		throw new Error(
			`Not set: ${list.join(", ")}. Set them in .env, the shell, or as arguments (see README "Getting started").`
		);
	}
	return Object.fromEntries(
		names.map((name) => {
			const value = environment[name];
			const processor = PROCESSORS[name];
			return [
				name,
				processor ? processor(`${prefix}PUBLIC_${name}`, value) : value
			];
		})
	);
}

const HEADER =
	"// Generated by scripts/environments/generate.mjs; do not edit.";

function writeEnvironment(file, environment) {
	writeFileSync(
		`${OUTPUT_DIR}/${file}`,
		`${HEADER}
import { IEnvironment } from './environment.interface';

export const environment: IEnvironment = ${JSON.stringify(environment, null, "\t")};
`
	);
}

const productionValues = finalise(production, "PROD_");
const developmentValues = finalise(development, "DEV_");

// The folder is gitignored, so it doesn't exist in a fresh clone.
mkdirSync(OUTPUT_DIR, { recursive: true });
writeFileSync(
	`${OUTPUT_DIR}/environment.interface.ts`,
	`${HEADER}
export interface IEnvironment {
${names.map((name) => `\treadonly ${name}: string;`).join("\n")}
}
`
);
writeEnvironment("environment.ts", productionValues);
writeEnvironment("environment.development.ts", developmentValues);
// Crawlers only ever see the production site.
writeCrawlerFiles(productionValues.SITE_URL);
